type ValidPassword struct{ value string }

// Printable ASCII characters only; 15-64 characters
var passwordRegex = regexp.MustCompile(`^[\x20-\x7E]{15,64}$`)

func ValidatePassword(p string) (ValidPassword, error) {
	if !passwordRegex.MatchString(p) {
		return ValidPassword{}, ErrPswdInvalid
	}
	return ValidPassword{p}, nil
}

func (p ValidPassword) Hash() ([]byte, error) {
	const cost = 12
	return bcrypt.GenerateFromPassword([]byte(p.value), cost)
}

// Match returns true if the hash of this password matches passwordHash,
// which must be generated by [ValidPassword.Hash].
func (p ValidPassword) Match(passwordHash []byte) bool {
	return bcrypt.CompareHashAndPassword(passwordHash, []byte(p.value)) == nil
}

