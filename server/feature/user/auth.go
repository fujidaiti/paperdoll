type CanonicalEmail struct{ value string }

func ParseEmail(addr string) (CanonicalEmail, error) {
	for i := 0; i < len(addr); i++ {
		if addr[i] > unicode.MaxASCII {
			return CanonicalEmail{}, ErrEmailInvalid
		}
	}
	a, err := mail.ParseAddress(addr)
	if err != nil || a.Address != addr {
		return CanonicalEmail{}, ErrEmailInvalid
	}
	return CanonicalEmail{strings.ToLower(a.Address)}, nil
}

type Token [32]byte

func NewToken() (Token, error) {
	t := Token{}
	_, err := rand.Read(t[:])
	return t, err
}

func DecodeToken(t string) (Token, error) {
	b, err := base64.RawURLEncoding.DecodeString(t)
	if err != nil || len(b) != 32 {
		return Token{}, ErrTokenInvalid
	}
	return Token([32]byte(b)), nil
}

func (t Token) Encode() string {
	if t == (Token{}) {
		return ""
	}
	return base64.RawURLEncoding.EncodeToString(t[:])
}

func (t Token) Hash() []byte {
	if t == (Token{}) {
		return nil
	}
	h := sha256.Sum256(t[:])
	return h[:]
}

type VerificationCode string

type VerificationCodeGenerator = func() (VerificationCode, error)

var verificationCodeRegex = regexp.MustCompile(`^\d{6}$`)

func ParseVerificationCode(code string) (VerificationCode, bool) {
	if verificationCodeRegex.MatchString(code) {
		return VerificationCode(code), true
	}
	return "", false
}

func NewVerificationCode() (VerificationCode, error) {
	n, err := rand.Int(rand.Reader, big.NewInt(1_000_000))
	if err != nil {
		return "", err
	}
	return VerificationCode(fmt.Sprintf("%06d", n)), nil
}

func (c VerificationCode) Hash() []byte {
	if c == "" {
		return nil
	}
	h := sha256.Sum256([]byte(c))
	return h[:]
}

// Match returns true if the hash of this code matches the codeHash,
// which must be generated by [VerificationCode.Hash].
func (c VerificationCode) Match(codeHash []byte) bool {
	return subtle.ConstantTimeCompare(c.Hash(), codeHash) == 1
}

